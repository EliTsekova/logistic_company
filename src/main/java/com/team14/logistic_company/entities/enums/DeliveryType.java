package com.team14.logistic_company.entities.enums;

/**
 * Enumeration representing the available shipment delivery types.
 *
 * The delivery type determines whether the shipment
 * is delivered to a company office or directly to an address.
 */
public enum DeliveryType {

    /**
     * Shipment delivery to a company office.
     */
    TO_OFFICE,

    /**
     * Shipment delivery directly to a customer address.
     */
    TO_ADDRESS
}